/* Reproducible multinomial naive Bayes training; no service or user chats. */
'use strict';
const fs=require('node:fs'),path=require('node:path'),F=require('../src/product/coach-text-features');
const training=require('../tests/fixtures/coach-intent-training.json');
function train(){
 const vocab=new Set(),counts={},totals={};
 for(const [intent,examples] of Object.entries(training)){
  counts[intent]={};totals[intent]=0;
  for(const q of examples)for(const f of F.features(q)){vocab.add(f);counts[intent][f]=(counts[intent][f]||0)+1;totals[intent]++;}
 }
 const vocabulary=[...vocab].sort(),weights={};
 // Equal class priors keep corpus size from masquerading as intent frequency.
 for(const intent of Object.keys(training).sort())weights[intent]=vocabulary.map(f=>Math.round(Math.log(((counts[intent][f]||0)+1)/(totals[intent]+vocabulary.length))*1e6)/1e6);
 return {version:1,algorithm:'multinomial-naive-bayes',provenance:'Reviewer-authored synthetic training phrases; no athlete conversations.',examples:Object.values(training).reduce((n,v)=>n+v.length,0),vocabulary,weights};
}
function source(){return '/* Generated by node scripts/train-coach-intents.js; do not edit. */\n(function(root,factory){if(typeof module===\'object\'&&module.exports)module.exports=factory();else root.LoadnoteCoachIntentModel=factory();})(typeof globalThis!==\'undefined\'?globalThis:this,function(){return '+JSON.stringify(train())+';});\n';}
if(require.main===module){const target=path.join(__dirname,'../src/product/coach-intent-model.js');if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==source())throw Error('Intent model is stale; retrain it');console.log('Bundled intent model is reproducible');}else fs.writeFileSync(target,source());}
module.exports={train,source};
