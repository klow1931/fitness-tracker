const assert=require('node:assert/strict');
const Starter=require('../src/product/beginner-program');
const Custom=require('../src/product/custom-program');
const First=require('../src/product/beginner-first-week');
const B=require('../src/product/beginner-experience');
const Coach=require('../src/product/coach-conversation');
const asOf='2026-11-05',timezoneOffsetMinutes=300;
const empty={customPrograms:[],workouts:[],scheduledSessions:[],exerciseCatalog:[]};
const proposal=Starter.make(empty,{goal:'fitness',equipment:'gym',days:[0,2,4]},{asOf}).proposal;
const state=Custom.save(empty,proposal,{confirmed:true,id:'evening',now:'2026-11-06T01:30:00.000Z',source:{kind:'manual',name:'Loadnote beginner starting structure'}});
const before=JSON.stringify(state);
assert.equal(Starter.saved(state,{asOf}).length,0,'UTC default retains historical cutoff');
assert.equal(Starter.saved(state,{asOf,timezoneOffsetMinutes}).length,1,'evening local-day save remains available');
assert.equal(Starter.saved(state,{asOf:'2026-11-04',timezoneOffsetMinutes}).length,0,'future records remain excluded');
assert.equal(Starter.saved(state,{asOf,timezoneOffsetMinutes:-600}).length,0,'positive UTC-zone day boundaries stay bounded');
assert.equal(Starter.dayCutoff(asOf,300),'2026-11-06T04:59:59.999Z');
assert.equal(Starter.dayCutoff('2026-07-05',240),'2026-07-06T03:59:59.999Z');
assert.equal(Starter.dayCutoff(asOf,-330),'2026-11-05T18:29:59.999Z');
assert.throws(()=>Starter.dayCutoff(asOf,NaN));assert.throws(()=>Starter.dayCutoff(asOf,900));
assert.equal(Starter.selected({getItem:()=> 'evening'},state,{asOf,timezoneOffsetMinutes}),'evening');
assert.equal(First.inspect(state,{asOf,timezoneOffsetMinutes,entry:'help'}).action,'starter');
const scheduled=Custom.schedule(state,'evening',{now:'2026-11-06T02:00:00.000Z'});
assert.equal(Starter.saved(scheduled,{asOf,timezoneOffsetMinutes,unscheduled:true}).length,0);
const response=Coach.answer(state,'What should I train today?',{asOf,live:{starterDateOffsetMinutes:300,starterPlanId:'evening'}});
assert.match(response.text,/saved but not scheduled/);
for(const q of ["What is RPE? I'm new to lifting.","I'm new to lifting. What does RPE mean?"]){
 const answer=Coach.answer(empty,q,{asOf});assert.match(answer.text,/two more reps/);assert.notEqual(answer.intent.topic,'beginner-help');
}
assert.equal(Coach.answer(empty,"I'm new to lifting and my knee hurts. What is RPE?",{asOf}).intent.topic,'health');
assert.equal(JSON.stringify(state),before);
const preference={view:'simple',entry:'log'};
const workout=(date,id='one')=>({id,date,exercises:[{type:'strength',name:'Goblet squat',sets:[{reps:8,weight:0}]}]});
const intro=B.earlyTraining({...state,workouts:[workout('2026-11-05'),workout('2026-11-06','future'),workout('invalid','bad')]},{asOf,preference});
assert.equal(intro.guided,true);assert.equal(intro.weekCount,1);assert.equal(intro.recent.length,1);
assert.equal(B.earlyTraining(state,{asOf,preference:{view:'full',entry:'log'}}).guided,false);
assert.equal(B.earlyTraining(state,{asOf,preference:{view:'simple',entry:null}}).guided,false);
assert.equal(B.earlyTraining({...state,programmingProfiles:[{}]},{asOf,preference}).guided,false);
assert.equal(B.earlyTraining({...state,workouts:[workout(asOf,'1'),workout(asOf,'2'),workout(asOf,'3')]},{asOf,preference}).guided,false);
console.log('v7.1: local-day starter availability, immutable selection, Coach question priority and progressive beginner presentation passed');
