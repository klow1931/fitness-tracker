const assert=require('node:assert/strict');
const Custom=require('../src/product/custom-program');
const Import=require('../src/product/custom-program-import');
const Schedule=require('../src/product/schedule');
const Lifecycle=require('../src/product/program-lifecycle');
const Cancellation=require('../src/product/program-cancellation');
const Core=require('../src/core/loadnote-core');
const Sync=require('../src/product/sync-model');
const Integrity=require('../src/product/data-integrity');

const csv='Week,Day,Exercise,Sets,Reps,Weight,Unit,RPE,Rest,Type,Minutes,Notes\n1,Monday,"Competition Squat",4,5,315,lb,7,180,strength,,"1st week"\n1,Wednesday,Easy Cycling,,,,,, ,cardio,20,Recovery\n2,Monday,Competition Squat,4,4,325,lb,8,180,strength,,Next week';
assert.deepEqual(Import.csv(csv).rows.length,3);
assert.equal(Import.csv('Week,Day,Exercise,Sets,Reps,Notes\n1,Monday,"Bench, Pause",3,5,"Line one\nLine two"').rows[0].exercise,'Bench, Pause');
assert.equal(Import.csv('Week\tDay\tExercise\tSets\tReps\n1\tMonday\tBench\t3\t5','\t').rows[0].exercise,'Bench');
assert.equal(Import.plainText('Week 1\nMonday\nCompetition Bench 3x5 @ 225 lb RPE 7').rows[0].weight,'225');
assert.throws(()=>Import.csv('Name,Sets,Reps\nBench,3,5'),/Week, Day and Exercise/);
assert.throws(()=>Import.csv('Week,Day,Exercise,Sets,Reps,Weight (plates)\n1,Monday,Bench,3,5,4'),/Unrecognized training target/);
assert.throws(()=>Import.json('{"schemaVersion":32,"workouts":[]}'),/not a standalone/);
assert.deepEqual(Import.fromTable([['Week','Day','Exercise','Sets','Reps','Weight (lb)'],[1,'Monday','Pause Bench Press',3,6,225]],{source:'xlsx',sheetName:'Program'}).rows[0],{week:'1',day:'Monday',exercise:'Pause Bench Press',sets:'3',reps:'6',weight:'225',unit:'lb'});
assert.equal(Import.pdfItemsToText([{str:'Monday',transform:[0,0,0,0,0,20]},{str:'Week 1',transform:[0,0,0,0,0,40]},{str:'Squat 4x5',transform:[0,0,0,0,0,10]}]),'Week 1\nMonday\nSquat 4x5');

const savedState={schemaVersion:33,customPrograms:[],scheduledSessions:[],workouts:[],exerciseCatalog:[{id:'squat',name:'Competition Squat',aliases:[]}]};
const cfg={name:'My 2-week program',weeks:2,startDate:'2026-11-02',rows:Import.csv(csv).rows,unit:'lb'};
const p=Custom.build(savedState,cfg);
assert.equal(p.entries.length,3);
assert.equal(p.sessions.length,3);
assert.equal(p.sessions[0].date,'2026-11-02');
assert.equal(p.sessions[1].date,'2026-11-04');
assert.equal(p.sessions[0].exercises[0].sets.length,4);
assert.equal(p.sessions[0].exercises[0].sets[0].weight,142.88);
assert.equal(p.sessions[1].exercises[0].type,'cardio');
assert.equal(p.sessions[1].exercises[0].duration,20);
assert.throws(()=>Custom.build(savedState,{...cfg,startDate:'2026-11-03'}),/Monday/);
assert.throws(()=>Custom.build(savedState,{...cfg,rows:[{week:1,day:'Monday',exercise:'Bench',sets:3,reps:5,weight:225,unit:'unknown'}]}),/unit/);
assert.throws(()=>Custom.build(savedState,{...cfg,rows:[{week:1,day:'Monday',exercise:'Bench',sets:3,reps:5,rpe:11}]}),/RPE/);
assert.throws(()=>Custom.save(savedState,p,{confirmed:false}),/Review/);

let state=Custom.save(savedState,p,{confirmed:true,notes:'Follow my own spreadsheet.',source:{kind:'csv',name:'my-plan.csv'},now:'2026-10-18T12:00:00.000Z',id:'plan1'});
assert.equal(state.customPrograms.length,1);
assert.equal(state.customPrograms[0].source.name,'my-plan.csv');
assert.equal(state.customPrograms[0].review.notes,'Follow my own spreadsheet.');
assert.deepEqual(state.customPrograms[0].entries,p.entries);
assert.throws(()=>Custom.schedule({...state,scheduledSessions:Schedule.create([],{date:'2026-11-02',name:'Conflict',role:'mixed',goal:'Conflict',prescription:require('../src/product/session-intent').createPrescription([{name:'Other',type:'strength',sets:[{reps:5}]}],{type:'manual'},'2026-10-19T12:00:00.000Z')},{id:'other',now:'2026-10-19T12:00:00.000Z'})},'plan1'),/conflict/i);
state=Custom.schedule(state,'plan1',{now:'2026-10-19T12:00:00.000Z'});
assert.equal(Schedule.list(state.scheduledSessions).length,3);
assert.equal(Schedule.list(state.scheduledSessions)[0].prescription.plannedExercises[0].sets[0].weight,142.88);
assert.equal(Schedule.list(state.scheduledSessions)[1].prescription.plannedExercises[0].type,'cardio');
assert.throws(()=>Custom.schedule(state,'plan1'),/already scheduled/);
assert.equal(Lifecycle.inspect(state,{asOf:'2026-11-02'}).program.kind,'custom-program');
const cancelPreview=Cancellation.inspect(state,{programId:'plan1',kind:'custom-program',asOf:'2026-10-20'});
const cancelled=Cancellation.cancel(state,cancelPreview,{confirmed:true,reason:'Athlete wants a new start',asOf:'2026-10-20',now:'2026-10-20T12:00:00.000Z'});
assert.equal(Cancellation.isCancelled(cancelled,'plan1','custom-program'),true);
assert.equal(Lifecycle.programs(cancelled).length,0);
const restored=Cancellation.restore(cancelled,'custom-program:plan1',{confirmed:true,asOf:'2026-10-21',now:'2026-10-21T12:00:00.000Z'});
assert.equal(Cancellation.isCancelled(restored,'plan1','custom-program'),false);
assert.deepEqual(restored.customPrograms,state.customPrograms);
const before=JSON.stringify(state.customPrograms[0]);
const first=Schedule.list(state.scheduledSessions)[0];
state.workouts.push({id:'log1',date:first.date,createdAt:'2026-11-02T18:00:00.000Z',sessionIntent:{version:1,role:'mixed',goal:'Athlete-authored program; preserve original planned targets',prescription:first.prescription,deviationReason:'none',deviationNotes:'',schedule:{id:first.id,revisionAt:first.revisionAt}},exercises:[{name:'Competition Squat',exerciseId:'squat',type:'strength',sets:Array.from({length:4},()=>({reps:5,weight:142.88,rpe:8}))}]});
const review=Custom.insights(state,'plan1',{asOf:'2026-11-03'});
assert.equal(review.completed,1);
assert.equal(review.linkedSets,4);
assert.equal(review.matchedSets,4);
assert.equal(review.patterns[0].exposures,2);
assert.equal(JSON.stringify(state.customPrograms[0]),before);
const normalized=Core.normalizeState({schemaVersion:32,workouts:[]},{customPrograms:[]});
assert.equal(normalized.schemaVersion,33);
assert.deepEqual(normalized.customPrograms,[]);
assert.equal(Integrity.verifyBackupManifest(Integrity.addBackupManifest(state)).status,'verified');
assert.ok(Sync.COLLECTIONS.includes('customPrograms'));
assert.equal(Sync.project(state).collections.customPrograms.length,1);
console.log('Custom program import, scheduling, provenance and training evidence tests passed');
