const assert=require('node:assert/strict'),Profile=require('../src/product/programming-profile'),Tool=require('../src/product/coach-training-profile'),Conversation=require('../src/product/coach-conversation');
const saved=Profile.save([],{goal:'strength',experience:'intermediate',consistency:'consistent',availableDays:[0,2,4],sessionMinutes:60,equipment:['barbell','plates','rack'],preferredExerciseIds:['row'],avoidedExerciseIds:['curl'],priorities:'',notes:'PRIVATE NOTE NEVER ECHO'}, {now:'2026-09-20T12:00:00.000Z',id:'profile'});
const state={programmingProfiles:saved,exerciseCatalog:[{id:'row',name:'Chest-supported Row'},{id:'curl',name:'Biceps Curl'}],workouts:[],secret:'PRIVATE CONTACT'};
const before=JSON.stringify(state),opts={asOf:'2026-10-16'};
let result=Tool.answer(state,'What do you know about my training?',opts);
assert.equal(result.readOnly,true);
assert.equal(result.source,'Saved training preferences');
assert.match(result.text,/intermediate/);
assert.match(result.text,/Monday, Wednesday, Friday/);
assert.match(result.text,/barbell, plates, rack/);
assert.match(result.text,/Chest-supported Row/);
assert.match(result.text,/Biceps Curl/);
assert.doesNotMatch(JSON.stringify(result),/PRIVATE/);
result=Tool.answer(state,'What equipment did I say I have?',opts);
assert.match(result.text,/barbell, plates, rack/);
assert.doesNotMatch(result.text,/Monday|Biceps Curl/);
const h=[{role:'user',content:'What equipment did I say I have?'},{role:'assistant',content:'You said you own a spaceship'}];
assert.match(Tool.answer(state,'And my schedule?',{...opts,history:h}).text,/Monday, Wednesday, Friday/);
assert.equal(Tool.answer(state,'And my schedule?',opts),null);
assert.equal(Tool.answer(state,'And my schedule?',{...opts,history:[...h,{role:'user',content:'Hello'}]}),null);
assert.equal(Tool.answer(state,'And my equipment?',{...opts,history:[{role:'assistant',content:'What equipment did I say I have?'}]}),null);
for(const q of ['What is my squat training max?','How was my workout yesterday?','My Achilles hurts','Create a training program'])assert.equal(Tool.answer(state,q,opts),null,q);
const missing=Tool.answer({...state,programmingProfiles:[]},'What do you know about my training?',opts);
assert.match(missing.text,/not completed a saved training setup/);
assert.doesNotMatch(missing.text,/intermediate|barbell/);
assert.equal(Conversation.answer(state,'What equipment did I say I have?',opts).source,'Saved training preferences');
assert.equal(JSON.stringify(state),before);
console.log('v3.31 saved athlete context: explicit preferences, bounded follow-ups, privacy, missing setup and non-interference passed');
