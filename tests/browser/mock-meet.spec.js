 const host=page.locator('[data-mock-meet="meet12"]');
 await expect(host.locator('[data-meet-status]')).toHaveCount(9);
 const before=await page.evaluate(()=>JSON.stringify({workouts:data.workouts,scheduledSessions:data.scheduledSessions,original:data.meetCycles[0].sessions}));
 await host.locator('[data-meet-status="squat-0"]').selectOption('made');
 await host.locator('[data-meet-weight="squat-0"]').fill('150');
 await host.locator('[data-meet-status="squat-1"]').selectOption('missed');
 await host.locator('[data-meet-weight="squat-1"]').fill('165');
 await host.locator('[data-meet-status="bench-0"]').selectOption('made');
 await host.locator('[data-meet-weight="bench-0"]').fill('90');
 await host.locator('[data-meet-status="deadlift-0"]').selectOption('made');
 await host.locator('[data-meet-weight="deadlift-0"]').fill('190');
 await host.locator('[data-meet-status="deadlift-1"]').selectOption('passed');
 await expect(host.locator('[data-meet-weight="deadlift-1"]')).toBeDisabled();
 await host.locator('[data-meet-save]').click();
 await expect(host.locator('[data-meet-error]')).toContainText('confirm');
 await host.locator('[data-meet-confirm]').check();
 await host.locator('[data-meet-save]').click();
 await expect.poll(()=>page.evaluate(()=>data.meetCycles[0].mockMeet?.revisions.length)).toBe(1);
 expect(await page.evaluate(()=>JSON.stringify({workouts:data.workouts,scheduledSessions:data.scheduledSessions,original:data.meetCycles[0].sessions}))).toBe(before);
 const report=await page.evaluate(()=>LoadnoteMockMeet.inspect(data,{cycleId:'meet12',asOf:today()}));
