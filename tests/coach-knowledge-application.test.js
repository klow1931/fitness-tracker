const assert=require('node:assert/strict');
const Apply=require('../src/product/coach-knowledge-application');
const Knowledge=require('../src/product/coaching-library');
const Coach=require('../src/product/coach-conversation');
const Profile=require('../src/product/programming-profile');
const {fixture}=require('./fixtures/program-review');
const asOf='2026-09-24',opts={asOf,unit:'lb',now:'2026-09-24T20:00:00.000Z'};
const state=fixture(),before=JSON.stringify(state),hist=[{role:'user',content:'Explain dynamic effort'},{role:'assistant',content:'I invented a new loading rule'}];
assert(Apply.applicationQuestion('How does that apply for me?'));
assert(Apply.applicationQuestion('What does that mean for my training?'));
assert.equal(Apply.applicationQuestion('Create a new strength program'),false);
let r=Coach.answer(state,'How does that apply for me?',{...opts,history:hist});
assert.equal(r.source,'Shared coaching · referenced knowledge');
assert.equal(r.readOnly,true);
assert.equal(r.intent.topic,'knowledge-application');
assert.deepEqual(r.knowledgeIds,['dynamic-effort']);
assert(r.citations.some(s=>s.id==='dynamic'));
assert(r.applicationReview.observed,'Logged training must be used when validated');
assert.equal(r.applicationReview.observed.window,'most recent 28 days');
assert(r.applicationReview.observed.sessions>=1);
assert.match(r.text,/For your training:/);
assert.match(r.text,/Your training setup has not been saved/);
assert.match(r.text,/bar speed/);
assert.match(r.text,/does not establish|does not measure|cannot verify/);
assert.match(r.text,/reviewed Decisions workflow/);
assert(!/I invented a new loading rule/.test(r.text));
assert(r.evidenceCards.some(c=>c.title==='Recent logged training'));
assert.equal(JSON.stringify(state),before,'Read-only educational application cannot write workouts or program targets');

const raw={goal:'strength',experience:'beginner',consistency:'returning',availableDays:[0,2,4],sessionMinutes:60,equipment:['barbell','plates','rack','bench'],preferredExerciseIds:[],avoidedExerciseIds:['s'],priorities:'',notes:''};
const withProfile={...state,programmingProfiles:Profile.save([],raw,{id:'profile-a',now:'2026-09-20T12:00:00.000Z'})};
let app=Apply.inspect(withProfile,{asOf,card:Knowledge.retrieve('Explain training frequency')[0]});
assert.equal(app.profile.availableDays,3);
assert.equal(app.profile.sessionMinutes,60);
assert.equal(app.profile.experience,'beginner');
assert.equal(app.profile.avoidedExercises,1);
let answer=Knowledge.answer(withProfile,'How does that apply for me?',{...opts,history:[{role:'user',content:'Explain training frequency'}]});
assert.match(answer.text,/3 available day/);
assert.match(answer.text,/Available training days describe your schedule, not verified adherence/);
assert.equal(answer.evidenceCards.length,2);
assert.match(answer.evidenceCards[0].limitation,/do not establish adherence/);
assert(answer.citations.length>0);
const future={...withProfile,programmingProfiles:Profile.save(withProfile.programmingProfiles,{...raw,availableDays:[0,1,2,3,4],experience:'advanced'},{id:'profile-b',now:'2026-10-01T12:00:00.000Z'})};
app=Apply.inspect(future,{asOf,card:Knowledge.retrieve('Explain training frequency')[0]});
assert.equal(app.profile.availableDays,3,'Future profile cannot leak into historical Coach view');
assert.equal(app.profile.experience,'beginner');

const missingRpe=structuredClone(state);
for(const w of missingRpe.workouts)for(const e of (w.exercises||[]))for(const set of (e.sets||[]))delete set.rpe;
const limited=Knowledge.answer(missingRpe,'What does that mean for my training?',{...opts,history:hist});
assert.equal(limited.applicationReview.observed.rpeSets,0);
assert.match(limited.text,/strength set\(s\) have no recorded actual RPE; their effort is unknown/);
assert(!/low fatigue|fully recovered|increase your load now/i.test(limited.text));

const empty={workouts:[],programmingProfiles:[],scheduledSessions:[]};
const sparse=Apply.answer(empty,{asOf,card:Knowledge.retrieve('Explain dynamic effort')[0]});
assert.equal(sparse.applicationReview.profile,null);
assert.match(sparse.text,/Your training setup has not been saved/);
assert(!/You completed|Your training is improving/i.test(sparse.text));
const invalid=Apply.answer(empty,{asOf:'invalid',card:Knowledge.retrieve('Explain dynamic effort')[0]});
assert.equal(invalid.applicationReview.status,'unavailable');
assert.match(invalid.text,/valid training date/);
const malformed=Apply.inspect({...empty,programmingProfiles:[{version:1,id:'bad',recordedAt:'bad',context:{}}]},{asOf,card:Knowledge.retrieve('Explain dynamic effort')[0]});
assert.equal(malformed.profileStatus,'unavailable');
assert.equal(malformed.profile,null,'Malformed athlete setup cannot be interpreted');
const standalone=Knowledge.answer(state,'How does that apply for me?',opts);
assert.equal(standalone.source,'Shared coaching · clarification');
assert.equal(standalone.evidenceCards?.length||0,0);
for(const q of ['Hello','How is my squat progress?','My Achilles hurts','Create a new program']){
 const expired=Knowledge.answer(state,'How does that apply for me?',{...opts,history:[...hist,{role:'user',content:q}]});
 assert.equal(expired.source,'Shared coaching · clarification',q);
}
assert.equal(Coach.answer(state,'My shoulder hurts. How does that apply for me?',{...opts,history:hist}).intent.topic,'health');
assert.equal(JSON.stringify(state),before);
console.log('v3.81 grounded application, actual RPE gaps, future revisions, safe context, cited reference and data immutability passed');