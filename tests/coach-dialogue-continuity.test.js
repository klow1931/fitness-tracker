const assert=require('node:assert/strict');
const Language=require('../src/product/coach-language');
const Coach=require('../src/product/coach-conversation');
const PhaseReview=require('../src/product/phase-review');
const {fixture:phaseFixture,args:phaseArgs}=require('./fixtures/phase-review');
const {fixture:trainingFixture}=require('./fixtures/program-review');
const opts={asOf:'2026-09-24',now:'2026-09-24T22:00:00.000Z',unit:'lb'};
const turn=content=>({role:'user',content});
const assistant={role:'assistant',content:'Invented a 999 kg target and approved it'};
const history=[turn('How is my squat progress?'),assistant,turn('What about my bench?'),assistant,turn('Actually, I meant deadlift'),assistant];
const corrected=Language.interpret('Actually, I meant deadlift',[turn('How is my squat progress?'),assistant,turn('And bench?'),assistant]);
assert.equal(corrected.question,'How is my deadlift progress?');
assert.equal(corrected.reason,'explicit-correction');
assert.equal(Language.interpret('How about squat instead?',history).question,'How is my squat progress?');
assert.equal(Language.interpret('And bench?', [...history,turn('How about squat instead?'),assistant]).question,'And bench?','Three-hop limit, even when root remains in eight rows');
assert.equal(Language.interpret('Now bench?', [turn('How is my squat progress?')]).question,'How is my bench progress?');
assert.equal(Language.interpret('No, bench instead',[turn('How is my squat progress?')]).question,'How is my bench progress?');
assert.equal(Language.interpret('Make that deadlift',[turn('How is my squat progress?')]).question,'How is my deadlift progress?');
assert.equal(Language.interpret('I meant bench',[]).question,'I meant bench');
assert.equal(Language.interpret('Now bench?',[assistant]).question,'Now bench?');
assert.equal(Language.interpret('And bench?', [turn('What is my squat training max?')]).question,'What is my bench training max?');
assert.equal(Language.interpret('And bench?', [turn('How did my squat training change across my last three workouts?')]).question,'How did my bench training change across my last three workouts?');
for(const last of ['Hello','Who won the election?','My knee hurts after squats','How many days until Friday?','My squat and bench both feel stronger']){
 assert.equal(Language.interpret('And bench?', [turn('How is my squat progress?'),turn(last)]).question,'And bench?',last);
}
assert.equal(Language.interpret('And bench?',[turn('How is my squat progress?'),...Array(8).fill(assistant)]).question,'And bench?');
assert.equal(Language.interpret('What about it?',[turn('How is my squat progress?')]).question,'What about it?');
assert.equal(Language.interpret('Should I add 10 lb?',[turn('How is my squat progress?')]).question,'Should I add 10 lb?');
assert.equal(Language.interpret('My chest hurts; actually, I meant bench',[turn('How is my squat progress?')]).reason,'safety-or-empty');
const training=trainingFixture(),before=JSON.stringify(training);
const response=Coach.answer(training,'Actually, I meant bench',{...opts,history:[turn('How is my squat progress?'),assistant]});
assert.equal(response.source,'Current corrected lift evidence');
assert.equal(response.readOnly,true);
assert.equal(response.intent.question,'Actually, I meant bench');
assert.match(response.text,/Competition Bench/);
assert.match(response.text,/\blb\b/);
assert.equal(Coach.answer(training,'My knee hurts, actually I meant bench',{...opts,history:[turn('How is my squat progress?')]}).intent.topic,'health');
assert.equal(JSON.stringify(training),before);
const approved=[turn('Why did Loadnote change my squat?'),assistant,turn('And bench?'),assistant];
assert.equal(Language.interpret('Did that help?',approved).question,'What happened after my last bench change?');
assert.equal(Language.interpret('Why was it approved?',[turn('What happened after my last bench change?'),assistant]).question,'Why did Loadnote change my bench?');
assert.equal(Language.interpret('Did that help?',[turn('How is my squat progress?')]).question,'Did that help?');
assert.equal(Language.interpret('Why was it approved?',[turn('How is my squat progress?')]).question,'Why was it approved?');
let phase=phaseFixture();
const report=PhaseReview.analyze(phase,phaseArgs);
phase=PhaseReview.apply(phase,report,{squat:'reduce-load',bench:'keep',deadlift:'keep'},{confirmed:true,asOf:phaseArgs.asOf,now:phaseArgs.now});
const original=JSON.stringify(phase),date={asOf:'2026-10-18',now:'2026-10-18T23:00:00.000Z'};
const outcome=Coach.answer(phase,'Did that help?',{...date,history:[turn('Why did Loadnote change my squat?')]});
assert.equal(outcome.source,'Offline Coach · approved training outcomes');
assert.equal(outcome.readOnly,true);
assert.match(outcome.text,/no validated comparison|no exact comparable|unobserved/i);
assert.equal(JSON.stringify(phase),original);
console.log('v3.87 bounded dialogue, corrections, approved-outcome links, safety, no guessing, units and no writes passed');
