assert.equal(r.revision,2);assert.equal(r.records[0].createdAt,now);assert.equal(r.records[0].text,'Enjoy training consistently');
r=a.save({type:'follow-up',text:'Ask if I put my phone away before cooking'},{expectedRevision:2,confirmed:true});
assert.equal(a.read().nextVisit.length,0,'The note must not interrupt the creating visit');
const reloaded=M.createStore(storage,'local-device',{visit:'visit-second-02',clock:()=>later});
assert.equal(reloaded.read().nextVisit.length,1,'A new visit offers only the approved follow-up');
assert.match(reloaded.read().nextVisit[0].text,/phone away/);
assert.equal(a.read().nextVisit.length,0);
