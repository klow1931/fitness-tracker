assert.throws(()=>a.save({type:'routine-cue',text:'Prepare gym clothes'},{expectedRevision:0,confirmed:true}),/changed/);
assert.throws(()=>a.save({type:'reason',text:'My injury is serious'},{expectedRevision:1,confirmed:true}),/non-sensitive/);
assert.throws(()=>a.save({type:'reason',text:'My password is secret'},{expectedRevision:1,confirmed:true}),/non-sensitive/);
assert.throws(()=>a.save({type:'reason',text:'  spaces  '},{expectedRevision:1,confirmed:true}),/short/);
assert.equal(a.read().records.length,1);
