assert.equal(other.read().records.length,0,'Account scopes cannot see one another');
assert.equal(M.owner({status:'unknown'}),null);
assert.equal(M.owner({status:'authenticated',account:{id:'athlete-A'}}),'account:athlete-A');
assert.equal(M.owner({status:'anonymous'}),'local-device');
assert.equal(M.owner({status:'authenticated',account:{id:'bad/id'}}),null);
assert.throws(()=>account.importData(copy,{expectedRevision:0,confirmed:true}),/another profile/);
assert.equal(account.read().records.length,0);
assert.throws(()=>account.importData(copy,{expectedRevision:0}),/another profile/);
assert.throws(()=>a.importData(JSON.stringify({...JSON.parse(copy),records:[{...goal,id:'bad'}]}),{expectedRevision:3,confirmed:true}),/Invalid memory ID/);
assert.equal(a.read().records.length,2);
const exported=JSON.parse(copy);
assert(!JSON.stringify(exported).includes('workouts'));
assert.equal(exported.scope,'local-device');
const refreshed=M.createStore(storage,'local-device',{visit:'visit-third-003',clock:()=>later});
