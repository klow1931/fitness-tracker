const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
function node(){
 return {style:{},children:[],events:{},append(child){this.children.push(child);},addEventListener(type,fn,options){this.events[type]={fn,options};}};
}
const document={createElement:()=>node(),querySelector:()=>null};
let opened=0,closed=0;
const window={LoadnoteOfflinePlannerUI:{open:()=>opened++},LoadnoteCoachCompanionUI:{close:()=>closed++}};
vm.runInNewContext(fs.readFileSync(require.resolve('../src/product/smart-coach-ui'),'utf8'),{window,document,Date,Math});
const host=node();
window.LoadnoteSmartCoachUI.attach(host,{actions:[{kind:'offline-plan',label:'Draft my workout',request:{kind:'daily'}}]});
const button=host.children[0].children[0];
assert.equal(button.style.touchAction,'manipulation');
const mouseDown={button:0,prevented:false,preventDefault(){this.prevented=true;}};
button.events.mousedown.fn(mouseDown);
assert.equal(mouseDown.prevented,true,'mouse press must not scroll the Coach chat away from its action');
const rightClick={button:2,prevented:false,preventDefault(){this.prevented=true;}};
button.events.mousedown.fn(rightClick);
assert.equal(rightClick.prevented,false,'context click remains native');
button.events.click.fn({detail:1});
assert.equal(opened,1,'mouse click opens the review');
button.events.click.fn({detail:0});
assert.equal(opened,2,'keyboard click opens the review');
assert(button.events.touchstart&&button.events.touchend&&button.events.touchcancel,'WebKit touch must have a dedicated fallback');
assert.equal(button.events.touchstart.options.passive,true,'touch start must not block vertical scrolling');
assert.equal(button.events.touchend.options.passive,false,'touch end can cancel a ghost click after activation');
const touch=(x,y,id=7)=>({clientX:x,clientY:y,identifier:id});
const start=()=>button.events.touchstart.fn({touches:[touch(20,30)]});
const end=()=>{const e={changedTouches:[touch(20,30)],cancelable:true,prevented:false,preventDefault(){this.prevented=true;}};button.events.touchend.fn(e);return e;};
start();const t=end();assert.equal(t.prevented,true,'prevent compatibility click into the opened modal');
assert.equal(opened,3,'a stationary mobile tap opens exactly one review');
button.events.click.fn({detail:1});
assert.equal(opened,3,'a compatibility click must not reopen or close the dialog');
button.events.click.fn({detail:0});
assert.equal(opened,4,'assistive-technology click still works after touch');
start();button.events.touchmove.fn({touches:[touch(20,75)]});end();
assert.equal(opened,4,'a scrolling swipe is never an action');
start();button.events.touchcancel.fn();end();
assert.equal(opened,4,'cancelled touches never activate');
button.events.touchstart.fn({touches:[touch(20,30,1),touch(21,31,2)]});end();
assert.equal(opened,4,'multi-touch never activates');
assert.equal(closed,4,'each real activation closes the companion only once');
console.log('Coach action handles mouse, keyboard and stationary WebKit taps once, with no ghost clicks or scroll activation');
