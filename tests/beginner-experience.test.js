const assert=require('node:assert/strict');
const B=require('../src/product/beginner-experience');
const values=new Map();
const storage={getItem:key=>values.get(key)??null,setItem:(key,value)=>values.set(key,value)};
assert.deepEqual(B.read(storage),{view:'full',entry:null,guide:'active',step:0});
const athlete={experience:'advanced',maxes:{squat:200},workouts:[{sets:[{reps:5,rpe:null}]}]};
const before=JSON.stringify(athlete);
let p=B.write(storage,B.read(storage),{view:'simple',entry:'log'});
assert.equal(B.read(storage).view,'simple');assert.equal(B.read(storage).entry,'log');
p=B.write(storage,p,{step:3,guide:'skipped'});
assert.equal(B.read(storage).guide,'skipped');
p=B.write(storage,p,{guide:'active',step:0});
assert.equal(p.step,0);assert.equal(p.guide,'active');
assert.equal(JSON.stringify(athlete),before,'Presentation preferences must not mutate training data');
assert.deepEqual(B.normalize({view:'bad',entry:'bad',guide:'bad',step:99}),{view:'full',entry:null,guide:'active',step:3});
assert.equal(B.normalize({step:NaN}).step,0);
assert.equal(B.normalize({step:-5}).step,0);
values.set(B.KEY,'{broken');assert.equal(B.read(storage).view,'full');
assert.equal(B.read({getItem(){throw Error('denied');}}).view,'full');
const current=B.normalize();assert.throws(()=>B.write({setItem(){throw Error('quota');}},current,{view:'simple'}));
assert.equal(current.view,'full');
assert.equal(B.steps.length,4);assert(B.steps[1].body.includes('leave it blank'));assert(B.steps[3].body.includes('does not save'));
console.log('Beginner view preference normalization, persistence, failure and non-mutation tests passed');
