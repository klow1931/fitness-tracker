const assert=require('node:assert/strict');
const Setup=require('../src/product/program-setup-policy');
const Brief=require('../src/product/phase-review-brief');
const Review=require('../src/product/phase-review');
const {fixture,args}=require('./fixtures/phase-review');

const novice=Setup.recommend({experience:'beginner',consistency:'consistent',availableDays:[0,2,4,5]});
assert.equal(novice.style,'linear');
assert.equal(novice.trainingMaxKg,null,'never infer a training max');
assert.equal(novice.status,'ready');
const experienced=Setup.recommend({experience:'intermediate',consistency:'consistent',availableDays:[0,2,4,5]});
assert.equal(experienced.style,'undulating');
assert.match(experienced.reason,/suggestion, not evidence/i);
const returning=Setup.recommend({experience:'advanced',consistency:'returning',availableDays:[0,2,4]});
assert.equal(returning.style,'linear','recent adherence takes precedence over nominal experience');
const limited=Setup.recommend({experience:'advanced',consistency:'consistent',availableDays:[0,4]});
assert.equal(limited.style,'linear');
assert.equal(Setup.recommend({experience:'advanced',consistency:'consistent',availableDays:[0,2,4]},{hasLightExposure:false}).style,'linear');
const invalid=Setup.recommend({experience:'advanced',consistency:'consistent',availableDays:[0,2,4]},{days:[0,2,6]});
assert.equal(invalid.status,'needs-review');
assert.match(invalid.reason,/availability/);
assert.equal(Setup.recommend({experience:'intermediate',consistency:'consistent',availableDays:[0,2,4]},{meet:true}).trainingMaxKg,null);
const state=fixture(),original=JSON.stringify(state);
const report=Review.analyze(state,args);
const b=Brief.inspect(report,{squat:'reduce-load',bench:'keep',deadlift:'keep'});
assert.equal(b.lifts[0].recommendation,'reduce-load');
assert.equal(b.lifts[0].requiresApproval,true);
assert.match(b.lifts[0].whatChanged,/eligible unperformed/i);
assert.match(b.lifts[0].whatChanged,/about 5%/i);
assert.equal(b.lifts[0].observed.expectedSessions,report.findings.squat.expectedSessions);
assert.equal(b.lifts[1].requiresApproval,false);
assert.match(b.lifts[1].whatChanged,/No change/);
assert.match(b.lifts[0].why,/effort caps/i);
assert.equal(b.lifts[0].evidence.length,6);
assert.equal(JSON.stringify(state),original,'inspecting evidence must not mutate training history');
assert.throws(()=>Brief.inspect(report,{squat:'progress'}),/Unsupported/);
const sparse=structuredClone(state);sparse.workouts=[];
const sparseReport=Review.analyze(sparse,args),summary=Brief.inspect(sparseReport);
assert.equal(summary.lifts[0].needsMoreEvidence,true);
assert(summary.lifts.every(x=>x.action==='keep'));
assert(summary.lifts.every(x=>x.evidence.some(e=>e.includes('No supported comparison'))));
const lb=Review.analyze({...state,unit:'lb'},args);
assert.deepEqual(Brief.inspect(lb),Brief.inspect(report),'display units must not change the evidence decision');
console.log('Phase 2 setup policy, guarded adaptation explanations, sparse evidence and unit independence passed');
