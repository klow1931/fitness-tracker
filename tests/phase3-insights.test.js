const assert=require('node:assert/strict');
const Progress=require('../src/product/progress-story');
const Highlights=require('../src/product/progress-highlights');
const Trend=require('../src/product/coach-performance-insights');
const Coach=require('../src/product/coach-conversation');
const Readiness=require('../src/product/decision-readiness');
const Weekly=require('../src/product/weekly-coaching');
const WeeklyInsights=require('../src/product/weekly-coaching-insights');
const {fixture:weekFixture,args:weekArgs}=require('./fixtures/weekly-coaching');

const asOf='2026-09-28';
const workout=(id,date,weight,rpe=8)=>({id,date,createdAt:date+'T20:00:00.000Z',exercises:[
 {type:'strength',trackBy:'reps',exerciseId:'b',name:'Competition Bench',sets:[{weight,reps:5,rpe}]}
]});
const roles=Readiness.replace([],[{exerciseId:'b',role:'competition',competitionLift:'bench'}],{now:'2026-07-01T00:00:00.000Z',createId:()=> 'role-b'});
const base={exerciseCatalog:[{id:'b',name:'Competition Bench'}],exerciseRoles:roles,scheduledSessions:[],phasePrograms:[],meetCycles:[],phaseReviews:[],
 workouts:[workout('b1','2026-07-10',100),workout('b2','2026-07-24',100),workout('r1','2026-09-07',100),workout('r2','2026-09-21',100)]};
const frozen=JSON.stringify(base);
const report=Progress.analyze(base,{asOf,weeks:12});
const overview=Highlights.inspect(report);
assert.equal(overview.metrics[0].label,'Workouts logged');
assert.equal(overview.metrics[0].value,2,'recent 28-day window only');
assert.equal(overview.metrics[1].value,2);
assert.equal(overview.metrics[2].value,'100%');
assert.equal(overview.consistency.status,'logged');
assert.equal(overview.direction.status,'similar');
assert.match(overview.note,/not readiness/i);
let answer=Trend.answer(base,'Why has my bench stalled?',{asOf,unit:'lb'});
assert.equal(answer.readOnly,true);
assert.equal(answer.source,'Offline Coach · corrected training trends');
assert.match(answer.text,/does not prove a physiological plateau/i);
assert.match(answer.text,/lb/);
assert.equal(answer.evidence[0].baselineDays,2);
assert.equal(answer.evidence[0].recentDays,2);
assert.equal(Trend.answer(base,'How do I increase my bench?',{asOf}),null,'generic prescriptions are not redirected');
assert.equal(Trend.answer(base,'My training plateaued',{asOf}).readOnly,true);
const freshContext=[{role:'user',content:'Is my bench trend flat?'}];
assert.equal(Trend.answer(base,'Why is it stalled?',{asOf,history:freshContext}).intent.lift,'bench');
assert.match(Trend.answer(base,'Why is it stalled?',{asOf,history:[...freshContext,{role:'user',content:'Tell me about accessories'}]}).text,/Which lift/);
const routed=Coach.answer(base,'Why has my bench stalled?',{asOf,unit:'kg'});
assert.equal(routed.source,'Offline Coach · corrected training trends','conversational Coach must use the same derived evidence');
assert.equal(routed.intent.lift,'bench');
const future={...base,workouts:[...base.workouts,workout('future','2026-10-04',200)]};
assert.equal(Trend.answer(future,'Why has my bench stalled?',{asOf,unit:'kg'}).text,Trend.answer(base,'Why has my bench stalled?',{asOf,unit:'kg'}).text,'future logs cannot rewrite past answers');
const sparse={...base,workouts:[workout('first','2026-07-10',100,null),workout('last','2026-09-21',105,null)]};
answer=Trend.answer(sparse,'My bench progress has plateaued',{asOf});
assert.match(answer.text,/not enough comparable RPE-aware evidence/i);
assert.equal(answer.evidence[0].status,'insufficient');
assert.equal(Highlights.inspect(Progress.analyze(sparse,{asOf})).metrics[2].value,'0%','logged sets with unknown RPE mean zero coverage, not zero effort');
// No future evidence and no explicitly skipped/incomplete/warm-up sets in Progress.
const flagged=structuredClone(base);
flagged.workouts[3].exercises[0].sets.push({weight:300,reps:5,rpe:8,skipped:true});
flagged.workouts[3].exercises[0].sets.push({weight:310,reps:5,rpe:8,done:false});
flagged.workouts[3].exercises[0].sets.push({weight:320,reps:5,rpe:8,warmup:true});
const flaggedStory=Progress.analyze(flagged,{asOf,weeks:12});
assert.equal(flaggedStory.overview.recent.strengthSets,2);
assert.equal(flaggedStory.movements[0].recent.sets,2);
assert.equal(flaggedStory.movements[0].recent.bestLoad.weight,100);
assert.equal(JSON.stringify(base),frozen,'read-only trend queries must not edit workout history');
const wstate=weekFixture(),wsnapshot=JSON.stringify(wstate),w=Weekly.inspect(wstate,weekArgs);
const insights=WeeklyInsights.inspect(w);
assert.equal(insights.status,'ready');
assert(insights.items.some(x=>x.kind==='effort'));
assert(insights.items.some(x=>x.kind==='next'));
assert.match(insights.notice,/Only explicitly approved/);
assert(insights.items.length<=4);
const wMissing=Weekly.inspect(weekFixture({logged:false}),weekArgs);
assert(WeeklyInsights.inspect(wMissing).items.some(x=>x.kind==='missing'));
assert.equal(WeeklyInsights.inspect({status:'ambiguous'}).status,'unavailable');
const summary=Weekly.answer(wstate,'What stood out this week?',weekArgs);
assert.match(summary.text,/Effort above target/);
assert.equal(summary.readOnly,true);
assert.equal(JSON.stringify(wstate),wsnapshot,'weekly coaching must not write a decision');
console.log('Phase 3 descriptive Progress, plateau Coach, safe weekly observations, sparse data, unit boundaries and immutability passed');
