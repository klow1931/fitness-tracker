const assert=require('node:assert/strict');
const Starter=require('../src/product/beginner-program');
const Custom=require('../src/product/custom-program');
const asOf='2026-10-23',now='2026-10-23T12:00:00.000Z';
const state={exerciseCatalog:[],customPrograms:[],scheduledSessions:[],workouts:[{id:'history',date:'2026-10-01',exercises:[{name:'Squat',sets:[{weight:40,reps:6,rpe:null}]}]}]};
const before=JSON.stringify(state);
assert.equal(Starter.monday(asOf),'2026-10-26');
assert.equal(Starter.monday('2026-10-26'),'2026-10-26');
assert.throws(()=>Starter.monday('2026-02-30'));
assert.throws(()=>Starter.setup({goal:'fitness',equipment:'gym',days:[0]}),/two or three/);
assert.throws(()=>Starter.setup({goal:'fitness',equipment:'gym',days:[0,0]}),/two or three/);
assert.throws(()=>Starter.setup({goal:'strength',equipment:'unknown',days:[0,2]}),/goal and equipment/);
assert.throws(()=>Starter.setup({goal:'fitness',equipment:'gym',days:[0,2,4,6]}),/two or three/);
for(const goal of Object.keys(Starter.GOALS))for(const equipment of Object.keys(Starter.EQUIPMENT))for(const days of [[0,3],[0,2,4]]){
 const input={goal,equipment,days};
 const plan=Starter.make(state,input,{asOf});
 assert.equal(plan.proposal.config.weeks,4);
 assert.equal(plan.proposal.sessions.length,4*days.length);
 assert.equal(plan.proposal.entries.length,4*days.length*3);
 assert.deepEqual([...new Set(plan.proposal.sessions.map(s=>s.week))],[1,2,3,4]);
 assert(plan.proposal.entries.every(e=>e.weightKg===null&&e.rpe===null));
 assert(plan.proposal.sessions.every(s=>s.exercises.length===3));
 assert.equal(plan.proposal.config.startDate,'2026-10-26');
 assert.equal(JSON.stringify(state),before,'Preview must be read only');
}
const input={goal:'fitness',equipment:'bodyweight',days:[0,3]};
const original=Starter.make(state,input,{asOf});
const edited=original.slots.map(s=>s.exercises.map(e=>({...e})));
edited[0][0]={name:'My supported squat',sets:3,reps:10};
const reviewed=Starter.make(state,{...input,exercises:edited},{asOf});
assert.equal(reviewed.proposal.entries[0].name,'My supported squat');
assert.equal(reviewed.proposal.entries[0].reps,10);
assert.equal(reviewed.proposal.entries[6].name,'My supported squat','Same reviewed day repeats in subsequent weeks');
assert.throws(()=>Starter.make(state,{...input,exercises:[[{name:'',sets:3,reps:8}]]},{asOf}),/valid exercise/);
assert.throws(()=>Starter.make(state,{...input,exercises:edited.map(day=>day.map(e=>({...e,sets:9})))},{asOf}),/1–4 sets/);
assert.throws(()=>Custom.save(state,reviewed.proposal,{confirmed:false,now}),/confirm/);
const saved=Custom.save(state,reviewed.proposal,{confirmed:true,now,source:{kind:'manual',name:'Loadnote beginner starting structure'},notes:'Reviewed by athlete'});
assert.equal(saved.customPrograms.length,1);
assert.equal(saved.scheduledSessions.length,0);
assert.equal(saved.workouts[0].id,'history');
assert.equal(saved.customPrograms[0].entries[0].weightKg,null);
assert.equal(JSON.stringify(state),before,'Saving a new state must not mutate the previous state');
const scheduled=Custom.schedule(saved,saved.customPrograms[0].id,{now:'2026-10-23T12:10:00.000Z'});
assert.equal(scheduled.scheduledSessions.length,8);
assert.equal(scheduled.workouts[0].id,'history');
assert(scheduled.scheduledSessions.every(x=>x.revisions?.length>0));
assert.throws(()=>Custom.schedule(scheduled,scheduled.customPrograms[0].id,{now:'2026-10-23T12:20:00.000Z'}),/already scheduled|unavailable/);
assert.equal(JSON.stringify(state),before);
console.log('v3.93 starter goal/days/equipment, four-week read-only proposal, no loads or RPE, review/save/schedule boundaries passed');
