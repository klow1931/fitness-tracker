const assert=require('node:assert/strict');
const Intent=require('../src/product/session-intent'),F=require('../src/product/workout-feedback'),C=require('../src/product/coach-conversation');
const plan=Intent.createPrescription([{name:'Competition Bench',exerciseId:'bench1',type:'strength',trackBy:'reps',loadConvention:'total',sets:[{weight:100,reps:5,targetRpe:7},{weight:100,reps:5,targetRpe:7}]}],{type:'manual',label:'Test only'},'2026-10-10T17:00:00.000Z');
const workout=(id,date,sets,other={})=>({id,date,createdAt:date+'T19:00:00.000Z',sessionIntent:{prescription:plan},exercises:[{name:'Competition Bench',exerciseId:'bench1',type:'strength',loadConvention:'total',trackBy:'reps',sets}],...other});
const ok=workout('ok','2026-10-12',[{weight:100,reps:5,rpe:6},{weight:100,reps:5,rpe:7}]);
const above=workout('above','2026-10-13',[{weight:100,reps:5,rpe:8},{weight:100,reps:5,rpe:7}]);
const missing=workout('missing','2026-10-14',[{weight:100,reps:5},{weight:100,reps:5,rpe:7}]);
const changed=workout('changed','2026-10-15',[{weight:105,reps:5,rpe:7},{weight:100,reps:5,rpe:7}]);
const after=workout('after','2026-10-16',[{weight:100,reps:5,rpe:7},{weight:100,reps:5,rpe:7}],{sessionIntent:{prescription:{...plan,capturedAt:'2026-10-17T17:00:00.000Z'}}});
const noPlan=workout('no-plan','2026-10-11',[],{sessionIntent:null,exercises:[]});
const state={workouts:[ok,above,missing,changed,after,noPlan]};const before=JSON.stringify(state);
assert.equal(F.compare(ok).status,'within-cap');
assert.equal(F.compare(above).status,'above-cap');
assert.equal(F.compare(missing).status,'missing-effort');
assert.equal(F.compare(changed).status,'different-work');
assert.equal(F.compare(after).status,'unverified-timing');
assert.equal(F.compare(noPlan).status,'no-prior-plan');
const snapshot=F.analyze(state,{asOf:'2026-10-18',days:28});
assert.equal(snapshot.logged,6);assert.equal(snapshot.comparable,2);assert.equal(snapshot.unknown,4);assert.equal(snapshot.aboveCap,1);
assert.equal(snapshot.matchedSets,7);assert.equal(snapshot.effortCompared,6);
assert(snapshot.next.some(x=>x.includes('before approving changes')));
assert.equal(JSON.stringify(state),before,'Feedback cannot mutate athlete training');
const ask=F.answer(state,'Did I follow my workout plan?',{asOf:'2026-10-18'});
assert(ask.readOnly);assert.equal(ask.actions[0].kind,'training-feedback');
assert.match(ask.text,/2 fully comparable/);
assert.equal(F.answer(state,'What should my bench max be?',{asOf:'2026-10-18'}),null);
const coach=C.answer(state,'Compare planned versus actual',{asOf:'2026-10-18'});
assert.equal(coach.source,'Offline Coach · planned versus actual');
assert.throws(()=>F.analyze(state,{asOf:'2026-10-19',days:365}),/7- or 28-day/);
console.log('Planned-vs-logged observational feedback, evidence gaps, immutability and Coach routing passed');
