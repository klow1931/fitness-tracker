const assert=require('node:assert/strict');
const Recovery=require('../src/product/draft-recovery');
const Draft=require('../src/product/draft-model');
const key='loadnote-workout-draft-v1';
function storage(){
 const map=new Map();
 return {map,getItem:k=>map.get(k)||null,setItem(k,v){map.set(k,v);},removeItem(k){map.delete(k);}};
}
const sample=(weight,updatedAt=1)=>({version:3,date:'2026-10-17',notes:'',unit:'lb',updatedAt,rows:[{type:'strength',name:'Competition Bench Press',sets:[{weight,reps:'5',rpe:'8',done:true,showCompletion:true}]}]});
const s=storage();
assert.equal(Recovery.read(s,key,Draft.normalize),null);
assert.deepEqual(Recovery.write(s,key,sample('225')), {saved:true,redundant:true,recoveryOnly:false});
assert.equal(Recovery.read(s,key,Draft.normalize).rows[0].sets[0].weight,'225');
s.map.set(key,'{"incomplete":');
assert.equal(Recovery.read(s,key,Draft.normalize).rows[0].sets[0].weight,'225','corrupt primary recovers completed sets, lb unit and RPE');
s.map.set(key,JSON.stringify(sample('225',1)));
s.map.set(key+'-recovery',JSON.stringify(sample('230',2)));
assert.equal(Recovery.read(s,key,Draft.normalize).rows[0].sets[0].weight,'230','newer backup survives a failed primary write');
s.map.set(key,JSON.stringify(sample('235',3)));
assert.equal(Recovery.read(s,key,Draft.normalize).rows[0].sets[0].weight,'235','newest primary wins');
assert.equal(Recovery.clear(s,key),true);
assert.equal(Recovery.read(s,key,Draft.normalize),null,'committed workout must never resurrect');
const failed=storage();
failed.setItem=function(k,v){if(k===key)throw Error('quota');this.map.set(k,v);};
assert.deepEqual(Recovery.write(failed,key,sample('240')), {saved:true,redundant:false,recoveryOnly:true});
assert.equal(Recovery.read(failed,key,Draft.normalize).rows[0].sets[0].weight,'240','backup recoverable despite primary failure and retry warning');
const legacy=storage();
legacy.map.set(key,JSON.stringify(sample('200')));
assert.equal(Recovery.read(legacy,key,Draft.normalize).rows[0].sets[0].weight,'200','older one-copy drafts remain compatible');
const onlyPrimary=storage();
onlyPrimary.setItem=function(k,v){if(k===key+'-recovery')throw Error('recovery unavailable');this.map.set(k,v);};
assert.deepEqual(Recovery.write(onlyPrimary,key,sample('245',4)),{saved:true,redundant:false,recoveryOnly:false});
assert.equal(Recovery.read(onlyPrimary,key,Draft.normalize).rows[0].sets[0].weight,'245','primary-only is recoverable');
const neither=storage();
neither.map.set(key,JSON.stringify(sample('190',1)));
neither.setItem=()=>{throw Error('quota');};
assert.deepEqual(Recovery.write(neither,key,sample('250',3)),{saved:false,redundant:false,recoveryOnly:false});
assert.equal(Recovery.read(neither,key,Draft.normalize).rows[0].sets[0].weight,'190','both failed cannot claim the new checkpoint');
const resumed=storage();
resumed.map.set(key,JSON.stringify(sample('210',2)));
resumed.setItem=function(k,v){if(k===key)throw Error('primary unavailable');this.map.set(k,v);};
assert.equal(Recovery.write(resumed,key,sample('255',5)).recoveryOnly,true);
assert.equal(Recovery.read(resumed,key,Draft.normalize).rows[0].sets[0].weight,'255','newer recovery beats stale primary');
resumed.setItem=function(k,v){this.map.set(k,v);};
assert.deepEqual(Recovery.write(resumed,key,sample('260',6)),{saved:true,redundant:true,recoveryOnly:false});
assert.equal(Recovery.read(resumed,key,Draft.normalize).rows[0].sets[0].weight,'260','retry restores two valid copies');
assert.equal(Recovery.clear(resumed,key),true);
assert.equal(Recovery.read(resumed,key,Draft.normalize),null,'committed workout clears both copies');
console.log('v6.7 accurate draft checkpoint health, partial failures, retry, and data integrity passed');
